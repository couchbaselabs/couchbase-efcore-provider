"""Read and write the spec-test lists, and read the results of a run.

Shared by compare-baseline.py and find-flaky.py. known-failures.txt lists the tests expected to
fail, plus '# aborted: <class>' lines for test classes whose process crashed. flaky.txt lists the
tests that pass in some runs and fail in others. In both, each line is one test display name;
lines that start with '#' are comments, blank lines are skipped, and trailing whitespace is
ignored.
"""
import os
import sys

from trx import read_trx

PROJECT_DIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DEFAULT_BASELINE = os.path.join(PROJECT_DIR, "known-failures.txt")
DEFAULT_FLAKY = os.path.join(PROJECT_DIR, "flaky.txt")

ABORTED = "# aborted: "


def _lines(path):
    """Return the file's non-blank lines without trailing whitespace; stop if it does not exist."""
    if not os.path.isfile(path):
        sys.exit(f"No such file: {path}")
    with open(path) as f:
        return [line for line in (raw.rstrip() for raw in f) if line]


def read_baseline(path):
    """Return (tests, aborted classes) from known-failures.txt."""
    tests, aborted = set(), set()
    for line in _lines(path):
        if line.startswith(ABORTED):
            aborted.add(line[len(ABORTED):])
        elif not line.startswith("#"):
            tests.add(line)
    return tests, aborted


def write_baseline(path, failed, aborted):
    with open(path, "w") as f:
        f.write("# EF Core specification tests known to fail against this provider.\n")
        f.write("# Generated by scripts/run-suites.sh --update-baseline; the list may only shrink.\n")
        f.write("# Flaky tests are in flaky.txt instead; scripts/find-flaky.py --update moves them there.\n")
        for cls in sorted(aborted):
            f.write(f"{ABORTED}{cls}\n")
        for name in sorted(failed):
            f.write(name + "\n")


def read_flaky(path):
    return {line for line in _lines(path) if not line.startswith("#")}


def write_flaky(path, tests):
    with open(path, "w") as f:
        f.write("# EF Core specification tests that pass in some runs and fail in others.\n")
        f.write("# compare-baseline.py ignores their outcome; scripts/find-flaky.py adds to this list.\n")
        for name in sorted(tests):
            f.write(name + "\n")


def test_class(name):
    """The class part of a test display name: what comes before the method, ignoring arguments."""
    return name.partition("(")[0].rpartition(".")[0]


def read_results(results_dirs):
    """Return (passed, failed, aborted classes, classes run) for result directories read as one run.

    A directory's summary.tsv lists the classes that its run included. run-suites.sh deletes the
    TRX files of only those classes, so the TRX results of other classes are from an earlier run
    and are ignored. In a directory without summary.tsv, every TRX result counts, and the classes
    run are the classes of those results.
    """
    passed, failed, aborted, ran = set(), set(), set(), set()
    for results_dir in results_dirs:
        summary = os.path.join(results_dir, "summary.tsv")
        classes = None
        if os.path.exists(summary):
            classes = set()
            with open(summary) as f:
                for line in f:
                    # class, status, and (in newer summaries) the class's run time
                    cls, _, status = line.rstrip("\n").partition("\t")
                    status = status.partition("\t")[0]
                    classes.add(cls)
                    if status in ("aborted", "no-result"):
                        aborted.add(cls)
            ran |= classes
        for name, outcome, _ in read_trx(results_dir):
            cls = test_class(name)
            if classes is not None and cls not in classes:
                continue
            ran.add(cls)
            if outcome == "Passed":
                passed.add(name)
            elif outcome == "Failed":
                failed.add(name)
    return passed, failed, aborted, ran
